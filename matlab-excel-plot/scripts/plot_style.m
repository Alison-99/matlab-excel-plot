function cfg = plot_style(overrides)
% 统一样式入口；沿用用户已确定参数，字号单位 pt。
fonts=listfonts; font='Helvetica';
for candidate={'SimSun','Songti SC'}
    if any(strcmp(fonts,candidate{1})), font=candidate{1}; break; end
end
cfg=struct('FontName',font,'LegendFontName',font, ...
    'AxisFontSize',7,'XLabelFontSize',7.7,'YLabelFontSize',7.7, ...
    'LegendFontSize',8,'TitleFontSize',20,'FontWeight','normal', ...
    'TitleFontWeight','bold','Interpreter','none','AxisLineWidth',0.8, ...
    'BaseLineWidth',0.5,'MarkerSize',6,'TickDir','in', ...
    'TickLength',[0.01 0.025],'Box','on','Grid','off', ...
    'FigureWidthCm',24,'SingleHeightCm',18,'CombinedRowHeightCm',11, ...
    'ExportDPI',900,'BackgroundColor','white','Renderer','painters', ...
    'LegendMode','majority','LegendOrder',{{}},'StandardLegendOrder',{{}}, ...
    'MethodLabels',{{}},'MethodLineSpecs',{{}},'CopyExcel',true);
if nargin>0
    keys=fieldnames(overrides);
    for i=1:numel(keys)
        assert(isfield(cfg,keys{i}),'Unknown style setting: %s',keys{i});
        cfg.(keys{i})=overrides.(keys{i});
    end
end
assert(any(strcmp(cfg.LegendMode,{'majority','per-case'})),'Unknown LegendMode.');
end
